import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const source=await fs.readFile(new URL('../desktop/main.js',import.meta.url),'utf8');
const begin=source.indexOf('async function identityForStatus(');
const code=source.slice(begin,source.indexOf('\nfunction identityForRenderer(',begin));
let identity={installId:'fixture'};
let options;
const context=vm.createContext({identityPayload:async (_config,value)=>{options=value;return {...identity};}});
vm.runInContext(code,context);
const prepared={state:'ready',identity:{...identity},launcherProof:{usable:true},proofPreparedThisSession:true};
identity={...identity,minecraftUsername:'LinuxPlayer',minecraftUuid:'12345678-1234-1234-1234-123456789abc'};
let result=await context.identityForStatus({},prepared,true);
assert.equal(result.minecraftUsername,'LinuxPlayer');
assert.equal(prepared.identity.minecraftUsername,'LinuxPlayer');
assert.equal(prepared.launcherProof,null,'A different account must not reuse the old proof');
assert.equal(prepared.proofPreparedThisSession,false);
prepared.launcherProof={usable:true};
await context.identityForStatus({},prepared,false);
assert.equal(options.allowProtectedStorage,false,'Preserve the macOS protected-storage gate');
assert.equal(prepared.launcherProof.usable,true,'Unchanged accounts retain their prepared proof');
identity={installId:'fixture',minecraftLauncherDetectedUsername:'LinuxPlayer',minecraftUsernameSyncWarning:'Account sync unavailable'};
result=await context.identityForStatus({},null,true);
assert.equal(result.minecraftUsername,undefined,'A local account hint must not fabricate remote registration');
assert.equal(result.minecraftLauncherDetectedUsername,'LinuxPlayer');
assert(source.includes('await identityForStatus(launcherConfig, usePreparedPrerequisites ? prepared : null, allowProtectedStorage)'));
console.log('Live account refresh, proof invalidation and pending registration checks passed.');
