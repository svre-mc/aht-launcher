import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {listPackage,extractFile} from '@electron/asar';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const resources=path.join(root,'release-builds/windows/win-unpacked/resources');
const asar=path.join(resources,'app.asar');const paths=listPackage(asar);
assert(!paths.some(p=>/native-guard[\\/]test|module\.cpp|fixture\.cpp|test-native-guard/.test(p)));
const metadata=JSON.parse(extractFile(asar,'package.json'));assert.equal(metadata.ahtLauncherVersion,'0.2.09');
assert(extractFile(asar,'desktop/main.js').toString().includes('ensureNativeGuard'));
assert(extractFile(asar,'src/minecraftLauncherProfile.js').toString().includes('-XX:+DisableAttachMechanism'));
const binary=await fs.readFile(path.join(resources,'native-guard/AHT Runtime Guard.exe'));
const manifest=JSON.parse(await fs.readFile(path.join(resources,'native-guard/manifest.json')));
assert.equal(crypto.createHash('sha256').update(binary).digest('hex'),manifest.sha256);
assert.deepEqual((await fs.readdir(path.join(resources,'native-guard'))).sort(),['AHT Runtime Guard.exe','NOTICE.txt','manifest.json']);
const result={passed:true,version:metadata.ahtLauncherVersion,guardSha256:manifest.sha256,guardBytes:binary.length,testFixturesExcluded:true,guardianWired:true,attachDisabled:true};
await fs.mkdir(path.join(root,'build/native-guard-test'),{recursive:true});
await fs.writeFile(path.join(root,'build/native-guard-test/package-results.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
